// Copies contract ABIs from Foundry's build output into src/abis so every app decodes events and
// encodes calls with exactly the ABI the contracts were compiled to. Run `forge build` first.
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const forgeOut = join(root, '..', '..', 'contracts', 'out');
const target = join(root, 'src', 'abis');

const contracts = [
  'LaunchFactory',
  'BondingCurve',
  'LaunchToken',
  'FeeVault',
  'GraduationLocker',
];

mkdirSync(target, { recursive: true });

const exports = [];
for (const name of contracts) {
  const artifact = JSON.parse(
    readFileSync(join(forgeOut, `${name}.sol`, `${name}.json`), 'utf8'),
  );
  const constName = `${name[0].toLowerCase()}${name.slice(1)}Abi`;
  const file = `${name}.ts`;
  writeFileSync(
    join(target, file),
    `// Generated by scripts/export-abis.mjs from contracts/out. Do not edit.\n` +
      `export const ${constName} = ${JSON.stringify(artifact.abi, null, 2)} as const;\n`,
  );
  exports.push(`export { ${constName} } from './${name}';`);
}

writeFileSync(join(target, 'index.ts'), `${exports.join('\n')}\n`);
console.log(`Exported ${contracts.length} ABIs to ${target}`);
